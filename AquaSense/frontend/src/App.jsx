import { useState } from 'react';
import { LayoutDashboard, Activity, BellRing, BarChart3, Cpu, Settings as Cog, Droplets, WifiOff } from 'lucide-react';
import { api, usePoll } from './api.js';
import { cx, StatusPill, Pill } from './ui.jsx';
import { Overview, Live, Alerts, Analytics, Sensor, SettingsPage } from './pages.jsx';

const NAV = [
  ['overview', 'Overview', LayoutDashboard, Overview], ['live', 'Live monitoring', Activity, Live], ['alerts', 'Alerts', BellRing, Alerts],
  ['analytics', 'Analytics', BarChart3, Analytics], ['sensor', 'Sensor', Cpu, Sensor], ['settings', 'Settings', Cog, SettingsPage],
];
const dayStart = () => new Date(new Date().setHours(0, 0, 0, 0)).toISOString();

export default function App() {
  const [page, setPage] = useState(() => location.hash.slice(1) || 'overview');
  const go = (id) => { location.hash = id; setPage(id); };
  const settings = usePoll(() => api('/settings'), 15000);
  const ms = (settings.data?.settings.refreshSeconds || 2) * 1000;
  const status = usePoll(() => api('/status?dayStart=' + encodeURIComponent(dayStart())), ms);
  const st = status.data, cfg = settings.data?.settings;
  const sim = cfg?.mode === 'simulation', src = sim ? 'simulator' : 'physical';
  const Page = (NAV.find((n) => n[0] === page) || NAV[0])[3];
  const reload = () => { settings.reload(); status.reload(); };
  const setMode = async (mode) => { try { await api('/settings', { method: 'PUT', body: { mode } }); reload(); } catch (e) { alert(e.message); } };
  const down = status.error;

  return (
    <div className="min-h-screen md:pl-56">
      <aside className="fixed inset-y-0 left-0 hidden w-56 flex-col border-r border-line bg-panel/60 p-4 md:flex">
        <div className="mb-6 flex items-center gap-2 text-lg font-semibold"><Droplets className="text-blue" size={22} />AquaSense</div>
        <nav className="space-y-1">
          {NAV.map(([id, label, Icon]) => (
            <button key={id} onClick={() => go(id)} className={cx('flex w-full items-center gap-3 rounded-lg px-3 py-2 text-sm', page === id ? 'bg-blue/15 text-blue' : 'text-slate-400 hover:bg-white/5')}>
              <Icon size={17} />{label}
            </button>
          ))}
        </nav>
        <p className="mt-auto text-xs text-slate-500">{cfg?.deviceName}<br />{cfg?.deviceId}</p>
      </aside>

      <header className="sticky top-0 z-20 flex flex-wrap items-center justify-between gap-2 border-b border-line bg-ink/90 px-4 py-3 backdrop-blur">
        <h1 className="text-base font-semibold">{NAV.find((n) => n[0] === page)?.[1]}</h1>
        <div className="flex items-center gap-3">
          <StatusPill system={st?.system} />
          <div role="group" aria-label="Data source" className="flex rounded-lg border border-line p-0.5 text-xs">
            {[['physical', 'Physical device'], ['simulation', 'Simulation']].map(([m, l]) => (
              <button key={m} onClick={() => setMode(m)} className={cx('rounded-md px-2.5 py-1', (sim ? 'simulation' : 'physical') === m ? (m === 'simulation' ? 'bg-violet text-ink' : 'bg-blue text-ink') : 'text-slate-400')}>{l}</button>
            ))}
          </div>
        </div>
      </header>

      {sim && <div className="bg-violet/20 px-4 py-1.5 text-center text-xs font-medium text-violet-200">SIMULATION MODE — every value shown is generated by the simulator, not measured by the sensor.</div>}
      {down && <div className="flex items-center gap-2 bg-alert/15 px-4 py-2 text-sm text-red-200"><WifiOff size={16} />{down}</div>}

      <main className="mx-auto max-w-6xl space-y-4 p-4 pb-24 md:pb-6">
        <Page status={st} settings={cfg} src={src} ms={ms} reload={reload} go={go} />
      </main>

      <nav className="fixed inset-x-0 bottom-0 z-20 grid grid-cols-6 border-t border-line bg-panel md:hidden">
        {NAV.map(([id, label, Icon]) => (
          <button key={id} onClick={() => go(id)} aria-label={label} className={cx('grid place-items-center py-3', page === id ? 'text-blue' : 'text-slate-500')}><Icon size={20} /></button>
        ))}
      </nav>
    </div>
  );
}
